package season4.painandgain

/**
 * ТИПЫ-ПЕРЕЧИСЛЕНИЯ И ЗАПИСИ, ОБЩИЕ ДЛЯ СТАДИЙ (v446, план архитектуры, 4.6 и этап 5) — уровень 0: ни от чего не зависят. Пока
 * `Posture` жила в файле стратега, мир, читающий постуру прошлого тика, импортировал стратега — ребро вверх; `Intent` жил в
 * бою, а перебирает замыслы командир; `ChaseSample` — у тактика, а пишет его стратег. Тип переезжает туда, откуда он виден
 * всем, кто им пользуется, без ребра против уровней.
 */

internal enum class Posture {
    HOLD, RETREAT, ANNIHILATE, FLAG, EVADE;

    /** Отход: армия уходит от врага — к дому (RETREAT) или от его массы (EVADE). Одно множество вместо двух полярностей
     *  `== RETREAT || == EVADE` / `!= RETREAT && != EVADE`, выписанных в девяти местах. */
    val withdrawing: Boolean get() = this == RETREAT || this == EVADE
}

/** Режим командира (v160): рубка со строем, гонка очков или поход. Раздача клеток — только режим FIGHT. */
internal enum class CmdMode { FIGHT, RACE, MARCH }

/** Замысел, по которому командир раздаёт клетки (v138): напор, удержание или уступка. */
/** Замыслы командира (v138). SPREAD (рассредоточение против веера) отвергнут гейтом — 130/131 в двух формах,
 *  и живьём проверить не успели: лимит загрузок кода на сервере кончился. */
internal enum class Intent { PRESS, HOLD, YIELD, FOCUS, KITE }

/** Тик погони за целью прижима: дистанция от наших мили, клетка цели и клетка нашего ближайшего мили (см. PRESS_GIVEUP, v96). */
/** РАЗМЕН, КАКИМ ЕГО ВИДИТ РЕШЕНИЕ О ЗАХВАТЕ (v459, второй шаг архитектуры, этап 6.2). Ворота захвата зовутся и из `runRunners` — ДО мер
 *  этого тика, и из `runArmy` — после них; до v459 они читали члены синглтона, которые меры переписывают посреди тика, и один и тот же
 *  вопрос получал ответ то по вчерашнему, то по сегодняшнему размену, а по тексту этого не было видно (находка 2.8 п. 7 плана). Теперь
 *  место вызова называет, что оно видит: `Prev.exchange` — прошлый тик, `meas.view` — этот. */
internal class ExchangeView(val stalled: Boolean, val exchangeLive: Boolean, val ourLostWindow: Int)

