 *  несмещённой выборке логов то же самое видно по `fled=` (приказов, перебитых бегством): 83 за матч в поражениях
 *  против 15 в победах при впятеро более коротких поражениях, `obey` 84 % против 97 %, `breakoff` 44 % против 10 %.
