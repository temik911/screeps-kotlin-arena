/** СМЕРТЕЛЬНОСТЬ КЛЕТКИ — ОДНО ПРАВИЛО НА ДВЕ ВЕТКИ (v524, см. `lethal` в Deal и `lethalNow` в Tactician).
 *
 *  Шестой случай класса «одна величина — два правила». Вето командира (`Deal.lethal`, v178) считает ВАЛОВОЙ
 *  входящий за ОДИН тик: `danOf(c, key) >= c.hits`. Оценка клетки у тактика (`lethalNow`, v215) считает ЧИСТЫЙ,
 *  за вычетом нашего лечения, за ДВА тика: `netDamageAt(...) * 2 >= hits`. Обе ведут ОДНОГО крипа в ОДНОМ тике.
 *
 *  Довод в пользу чистого записан у тактика и полностью применим к командиру: штампованное поле не знает про наше
 *  лечение, и клетка рядом с тремя живыми лекарями объявляется смертельной, хотя входящий там перекрыт с запасом
 *  (три лекаря вплотную дают 216 в тик). Пока лекари живы, расхождение постоянное, и оно бьёт ровно по той
