 *  оставшись, лекарь доставляет 72 вплотную (24 в двух-трёх клетках); уйдя, доставляет ноль и снижает входящий на
 *  `here − best`. Уход окупается, только когда снятого урона больше несделанного лечения — из-под одного стрелка
 *  снимается 60 и 72 не окупает, из-под двух 120 и окупает. Гейт 143 PASS, экспозиция на стенде 8,1 %
 *  (190610/2357826), в разбитом прежде сценарии 1,7 %.
 *
 *  Граница правки: только лекарь и только когда подопечный есть и ранен. Ступень `supportAloneNearFoe` (рядом нет
 *  ни одного своего) не трогается — там лечить некого; раздетый боец не трогается — он не доставляет ничего, и его
 *  уход из-под огня ничего не стоит. Прибор правки — `fuse=`; вердикт по нему и по `hstep=flee`, а не по счёту.
 *
 *  ⚠️ ОТВЕРГНУТО, И ПРЕЖДЕ ВСЕГО ПОТОМУ, ЧТО АРИФМЕТИКА ВЫШЕ НЕПОЛНА. Она сравнивает РАЗОВЫЕ величины: 72 лечения
