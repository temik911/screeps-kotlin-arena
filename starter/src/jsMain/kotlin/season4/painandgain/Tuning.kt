 *  не выходит, а дёргается внутри — на следующем тике он снова `inReach`, и часть этих проверок уже разрешает уход.
 *
 *  ЧТО ЭТИ ДВА ОТКАЗА (v518 и v519) УСТАНОВИЛИ ВМЕСТЕ. Бегство лекаря — не дефект, а СИМПТОМ: ни запретить его, ни
 *  усилить нельзя с пользой, потому что решается не оно. Лекарь не должен ПОПАДАТЬ в досягаемость его стрелков, и
 *  это свойство ПОСТРОЕНИЯ АРМИИ, а не поведения одного крипа. Следующие попытки — туда. */
internal const val USE_HEALER_STANDS = false

