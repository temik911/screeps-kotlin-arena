/** ПРИКАЗ ЛЕЧЕНИЯ ДЕЙСТВУЕТ И ВПЛОТНУЮ (v523, см. healAndShoot в Fight).
 *
 *  Пятый случай класса «правило записано, но действует не там». v183 (решение оператора: «не должно быть ничего,
 *  что идёт мимо командира») обещает в самом коде: «ПРИКАЗ ДЕЙСТВУЕТ НА ВСЕЙ ЛЕЧЕБНОЙ ДАЛЬНОСТИ… прежде назначенный
 *  пациент брался, только если он ВПЛОТНУЮ». Исполнено зеркально: `ordered` спрашивает ТОЛЬКО дальняя ветка, а
 *  ближняя выбирает соседа в одной клетке местным рангом и выходит по `continue`, до дальней не доходя. То есть
