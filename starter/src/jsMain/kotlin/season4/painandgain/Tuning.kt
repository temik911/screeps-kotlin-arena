 *
 *  Живой A/B против MetalicaX#17, 10 рук: 2-3 против 2-3 по счёту, но живых в конце 4,0 против 5,8, `hexp` 64,2 %
 *  против 28,8 %, а прибор цели пошёл В ПРОТИВОПОЛОЖНУЮ СТОРОНУ — `hstep=flee` 22,2 % у правки против 2,6 % у базы
