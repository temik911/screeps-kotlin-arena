 *  пределами его дальности по построению. Уводить крипа из зоны по одному — в этой арене невозможно. */
internal const val USE_HEALERS_OUT_OF_REACH = false

/** УХОД ЛЕКАРЯ ИЗ-ПОД ОГНЯ ОБЯЗАН ОКУПАТЬСЯ (v519, см. `fleeHopeless` и ступень `supportInReach` в `mustFlee`).
