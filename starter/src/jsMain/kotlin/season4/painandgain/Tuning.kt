 *
 *  ✅ ПРИНЯТО ЖИВЬЁМ вместе с USE_LETHAL_SAME_RULE. A/B против MetalicaX#17, 14-15 рук на сторону (серия
 *  остановлена на 29 из 32): счёт **6-8 (43 %) против 4-11 (27 %)** у базы, `hexp` 45,4 % против 49,5 %, живых в
 *  конце 6,4 против 4,2, очки 129525:52491 против 74445:32340. Прибор правки `heord=931/2270 = 41,0 %` — то есть
 *  в 41 % выборов ближней ветки лекарь теперь исполняет приказ вместо местного ранга. */
