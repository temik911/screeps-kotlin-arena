/** КЛЕТКА ОТХОДА НЕ ПЕРЕПИСЫВАЕТСЯ БОЕВОЙ РАСКЛАДКОЙ (v522, см. passMelee / passRanged / passStripped в Deal).
 *
 *  Дефект механический и виден по списку проходов: `passStraggler`, `passKeeper` и `passCatchall` начинаются с
 *  `if (c.id in out) continue`, а `passMelee`, `passRanged` и `passStripped` — нет. Проход отхода (`passRetreat`)
 *  идёт ПЕРВЫМ и выдаёт раненому, одинокому и ротирующемуся клетку по своему правилу — с единственным во всей
 *  раздаче слагаемым «ближе к медику» (v407/v408). Следующие три прохода выдают тем же крипам другую клетку по
 *  обычной боевой оценке, и правило «идти к лекарю» исчезает бесследно.
 *
 *  Цена названа приборами самого бота: за матч против MetalicaX#17 `sout=0/0/0` (выход раненого не сработал ни
 *  разу), `meet=0/0/0/0/0` (точка встречи с лекарем не создана ни разу), `rotset=0/434` (ротация по его фокусу
 *  мертва), при `rot=12`. Побочно `rotatingMeet` хранит уже брошенную клетку, и отдельный проход `meetWounded`
 *  ведёт ЛЕКАРЯ встречать раненого туда, где того не будет.
 *
 *  Почему это важно именно сейчас: замер 21.09.2026 показал, что наш раздетый боец стоит в 4,04 клетки от
 *  собственного лекаря (у соперника 1,99) и возвращает оружие за пять тиков в 10 % случаев против его 35 %, а
 *  лечение вплотную даёт 72 в тик против 24 с трёх и нуля с четырёх. Механизм, который должен это чинить, в коде
 *  есть с v276 и v407 — он просто не доживает до исполнения.
 *
 *  Прибор правки — `repass=` (сколько раз клетка отхода сохранена из всех проходов боевой раскладки).
 *
 *  ➖ ЖИВЬЁМ НЕ РАЗЛИЧИМА, и это честный вердикт, а не победа. A/B против MetalicaX#17, 19 рук: 3-6 (33 %) против
 *  3-7 (30 %) у базы, `hexp` 41,7 % против 42,4 %, живых 3,3 против 3,5 — всё внутри шума при работающем приборе
 *  (`repass=236/1681 = 14,0 %`). Тумблер оставлен включённым: правка устраняет механическую несогласованность
 *  (три прохода теперь ведут себя как остальные три, у которых проверка есть с самого начала) и ничего не ломает.
 *
 *  ⚠️ И вывод, который из этого следует для мёртвой ротации: дело НЕ только в перезаписи клетки. Раз сохранение
 *  клетки отхода исхода не двигает, значит правило «идти к лекарю» надо чинить не запретом на переразмещение, а
 *  слагаемым медика ВНУТРИ боевой оценки — там, где крип и получает клетку в подавляющем большинстве тиков. */
